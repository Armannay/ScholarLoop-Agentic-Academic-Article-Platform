#!/usr/bin/env node
/**
 * Prove the spec still generates a *usable* TypeScript client.
 *
 * `openapi-typescript` can emit a file for a spec that is wrong in ways a linter does
 * not catch: a `$ref` to a component nobody defined, an operation whose response has
 * no schema, a body typed `never`. So this script does three things:
 *
 *   1. regenerates `generated/api-schema.d.ts` from `openapi.yaml` (via the
 *      `x-openapi-ts` entry in `redocly.yaml`, so lint and client agree on the API);
 *   2. writes a small file of type assertions that *uses* the generated types the way
 *      the console will - operation ids, request bodies, response payloads, enums;
 *   3. runs `tsc --noEmit` over both, so a broken type fails here and not in the UI.
 *
 * Exit code 0 = the client compiles and the assertions hold.
 */

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SPEC_DIR = resolve(HERE, '..')
const GENERATED = resolve(SPEC_DIR, 'generated')
const SCHEMA = resolve(GENERATED, 'api-schema.d.ts')
const ASSERTIONS = resolve(GENERATED, 'type-assertions.ts')
const BIN = resolve(SPEC_DIR, 'node_modules', '.bin')

const run = (command, args) =>
  execFileSync(command, args, { cwd: SPEC_DIR, stdio: 'pipe', encoding: 'utf8' })

function fail(message, detail) {
  console.error(`\n✖ ${message}`)
  if (detail) console.error(detail.trim())
  console.error('')
  process.exit(1)
}

// ---------------------------------------------------------------- 1. regenerate
mkdirSync(GENERATED, { recursive: true })
try {
  run(resolve(BIN, 'openapi-typescript'), [])
} catch (error) {
  fail('openapi-typescript failed', `${error.stdout ?? ''}${error.stderr ?? ''}`)
}
if (!existsSync(SCHEMA)) fail('the client was not generated', SCHEMA)

const generated = readFileSync(SCHEMA, 'utf8')
for (const required of ['export interface paths', 'export interface components', 'export interface operations']) {
  if (!generated.includes(required)) fail(`generated client is missing ${required}`)
}
// GETs legitimately have `requestBody?: never`; the count is printed for context, not asserted.
const neverBodies = generated.match(/requestBody\??: never;/g) ?? []

// ---------------------------------------------------------------- 2. assertions
const assertions = `/**
 * Compile-time assertions over the generated client. GENERATED by scripts/client-check.mjs -
 * this file is a test, not a deliverable.
 *
 * Each \`Expect<\` line fails to compile if the client stops describing the API the
 * console is written against, which is the drift a JSON-schema check cannot see.
 */
import type { components, operations, paths } from './api-schema'

type Expect<T extends true> = T
type Equal<A, B> =
  (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false

type RunView = components['schemas']['RunView']
type RunState = components['schemas']['RunStateName']
type Brief = components['schemas']['Brief']
type ArticleSection = components['schemas']['ArticleSection']
type ErrorEnvelope = components['schemas']['ErrorEnvelope']
type CreateRun = paths['/api/projects/{project_id}/runs']['post']

// The run state vocabulary is closed: a typo cannot become a valid state.
export type _StateIsClosed = Expect<Equal<Extract<RunState, 'CHECKPOINT'>, 'CHECKPOINT'>>
const paused: RunState = 'CHECKPOINT'
// @ts-expect-error - 'CHECKPOINTED' is not one of the twelve states
const notAState: RunState = 'CHECKPOINTED'

// A run view carries the state, not the article body.
export type _RunHasState = Expect<Equal<RunView['state'], RunState>>
export type _RunHasNoMarkdown = Expect<Equal<'markdown' extends keyof RunView ? true : false, false>>

// The create-run body is a union of the two intake shapes, and neither is optional.
export type _CreateRunBody = Expect<
  Equal<
    CreateRun['requestBody'] extends { content: { 'application/json': infer Body } } ? true : false,
    true
  >
>
export type _CreateRunAccepted = Expect<Equal<CreateRun['responses'][202] extends never ? true : false, false>>

// ArticleSection is the SectionState contract plus exactly one body field.
export type _ArticleSectionHasText = Expect<Equal<ArticleSection['text'], string>>
export type _ArticleSectionNext = Expect<Equal<ArticleSection['text'] extends string ? true : false, true>>

// Errors are one envelope, and the code is a closed enum.
export type _ErrorCode = Expect<
  Equal<ErrorEnvelope['error']['code'] extends string ? true : false, true>
>

// A contract schema came through with its real fields, not an empty object.
export type _BriefTopic = Expect<Equal<Brief['topic'], string>>

// Every operation id the console calls exists.
export type _Operations = Expect<
  Equal<
    'createRun' extends keyof operations ? true : false,
    true
  >
>
export type _RunOps = Expect<
  Equal<'getRun' extends keyof operations ? true : false, true> &
    Equal<'answerRunDecision' extends keyof operations ? true : false, true> &
    Equal<'streamRunEvents' extends keyof operations ? true : false, true>
>

export const state: RunState = paused
export const typo: RunState = notAState
`
writeFileSync(ASSERTIONS, assertions, 'utf8')

// ---------------------------------------------------------------- 3. typecheck
try {
  run(resolve(BIN, 'tsc'), ['--noEmit', '-p', 'tsconfig.json'])
} catch (error) {
  fail('the generated client does not typecheck', `${error.stdout ?? ''}${error.stderr ?? ''}`)
}

console.log('\n✔ Typed client regenerated and typechecked\n')
console.log(`  schemas:    ${countSchemas(generated)} components`)
console.log(`  operations: ${countOperations(generated)} operation types`)
console.log(`  operations with no request body: ${neverBodies.length}`)
console.log(`  output:     ${SCHEMA.replace(`${SPEC_DIR}/`, '')} (git-ignored)\n`)

function countSchemas(text) {
  const start = text.indexOf('export interface components')
  const end = text.indexOf('export type $defs')
  const block = text.slice(start, end)
  return (block.match(/^        [A-Za-z$][\w$-]*: /gm) ?? []).length
}

function countOperations(text) {
  const start = text.indexOf('export interface operations')
  const block = text.slice(start)
  return (block.match(/^    [A-Za-z][\w]*: \{/gm) ?? []).length
}
