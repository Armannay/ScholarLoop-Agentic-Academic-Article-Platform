"""``make schemas`` - export every contract to docs/schemas/*.json.

Deterministic output: keys are sorted, files end with a newline, and ``--check``
fails (exit 1) when the committed schemas drift from the code. CI runs ``--check``,
so a contract edit without a re-export fails the build instead of silently
desynchronising the docs other steps generate code from.

Usage:
    python -m app.scripts.export_schemas --out docs/schemas
    python -m app.scripts.export_schemas --out docs/schemas --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from app import CONTRACT_VERSION
from app.contracts.registry import CONTRACTS, json_schema_for

INDEX_TEMPLATE = "# CONTRACTS v{version} JSON Schemas\n\n"
INDEX_NOTE = (
    "Generated by `make schemas` from `backend/app/contracts/`.\n"
    "Do not edit by hand: edit the Pydantic models and re-run the target.\n"
    'Every model is `extra="forbid"`; document models carry `schema_version = 1`;\n'
    "every schema declares `$schema` = JSON Schema draft 2020-12.\n"
    "Cross-field rules that JSON Schema cannot express (disjoint id lists, a\n"
    "`continue` verdict needing a target, BCP-47 language shape) live in model\n"
    "validators; see [../CONTRACT-AUDIT.md](../CONTRACT-AUDIT.md).\n\n"
)


def render_index() -> str:
    """Human-readable index of the exported schemas."""
    lines = [INDEX_TEMPLATE.format(version=CONTRACT_VERSION), INDEX_NOTE, "| Contract | Schema |\n"]
    lines.append("| --- | --- |\n")
    for name in CONTRACTS:
        lines.append(f"| `{name}` | [{name}.json]({name}.json) |\n")
    return "".join(lines)


def render_schema(name: str) -> str:
    """Stable, pretty-printed JSON for one contract (sorted keys, trailing newline)."""
    schema = json_schema_for(name)
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def export(out_dir: Path) -> list[Path]:
    """Write every schema; returns the written paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name in CONTRACTS:
        path = out_dir / f"{name}.json"
        path.write_text(render_schema(name), encoding="utf-8")
        written.append(path)
    index_path = out_dir / "README.md"
    index_path.write_text(render_index(), encoding="utf-8")
    written.append(index_path)
    return written


def check(out_dir: Path) -> list[str]:
    """Return the list of files that are missing or out of date."""
    stale: list[str] = []
    for name in CONTRACTS:
        path = out_dir / f"{name}.json"
        expected = render_schema(name)
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            stale.append(str(path))
    index_path = out_dir / "README.md"
    if not index_path.exists() or index_path.read_text(encoding="utf-8") != render_index():
        stale.append(str(index_path))
    return stale


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. Returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/schemas"))
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed schemas match the code instead of writing them",
    )
    args = parser.parse_args(argv)

    if args.check:
        stale = check(args.out)
        if stale:
            print("schemas are out of date; run `make schemas`:", file=sys.stderr)
            for path in stale:
                print(f"  - {path}", file=sys.stderr)
            return 1
        print(f"{len(CONTRACTS)} contract schemas are up to date in {args.out}")
        return 0

    written = export(args.out)
    print(f"wrote {len(written)} files to {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI wiring
    raise SystemExit(main())
